struct LegalView: View {
    var kind: LegalDocumentKind? = nil
    @State private var mapPrivacy = false
    var body: some View {
        if let kind {
            ScrollView {
                VStack(alignment: .leading, spacing: 24) {
                    Text("更新日期：2026 年 10 月 23 日").font(.subheadline).foregroundStyle(.secondary)
                    ForEach(LegalContent.sections(kind), id: \.0) { title, body in
                        VStack(alignment: .leading, spacing: 10) {
                            Text(title).font(.headline).accessibilityAddTraits(.isHeader)
                            Text(body).font(.body).foregroundStyle(Color.primary.opacity(0.68)).lineSpacing(6).textSelection(.enabled)
                        }
                    }
                    if kind == .thirdParties || kind == .privacy {
                        Button("高德开放平台隐私政策") { mapPrivacy = true }.frame(minHeight: 44)
                    }
                }.frame(maxWidth: .infinity, alignment: .leading).padding(24)
            }.background(Color(uiColor: .systemBackground))
                .navigationTitle(kind.title).navigationBarTitleDisplayMode(.inline)
                .sheet(isPresented: $mapPrivacy) { SafariPage(url: URL(string: "https://lbs.amap.com/pages/privacy/")!) }
        } else {
            List {
                ForEach(LegalDocumentKind.allCases) { document in
                    NavigationLink(document.title) { LegalView(kind: document) }
                }
            }.navigationTitle("隐私政策与用户协议").navigationBarTitleDisplayMode(.inline)
        }
    }
}
